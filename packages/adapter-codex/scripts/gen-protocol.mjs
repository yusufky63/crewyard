// Regenerates src/protocol/ from the installed codex CLI.
//
//   node packages/adapter-codex/scripts/gen-protocol.mjs
//
// `codex app-server generate-ts --experimental` writes the whole protocol (700+ files). We keep only
// the files reachable from ROOTS so the diff on a CLI upgrade shows what changed for us.

import { run as runCmd } from "@crewyard/proc";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOTS = [
  "InitializeParams",
  "InitializeResponse",
  "v2/ThreadStartParams",
  "v2/ThreadStartResponse",
  "v2/ThreadResumeParams",
  "v2/ThreadResumeResponse",
  "v2/TurnStartParams",
  "v2/TurnStartResponse",
  "v2/TurnSteerParams",
  "v2/TurnSteerResponse",
  "v2/TurnInterruptParams",
  "v2/TurnStartedNotification",
  "v2/TurnCompletedNotification",
  "v2/ItemStartedNotification",
  "v2/ItemCompletedNotification",
  "v2/AgentMessageDeltaNotification",
  "v2/ReasoningSummaryTextDeltaNotification",
  "v2/ReasoningTextDeltaNotification",
  "v2/CommandExecutionOutputDeltaNotification",
  "v2/ThreadTokenUsageUpdatedNotification",
  "v2/TurnDiffUpdatedNotification",
  "v2/TurnPlanUpdatedNotification",
  "v2/ErrorNotification",
  "v2/ServerRequestResolvedNotification",
  "v2/CommandExecutionRequestApprovalParams",
  "v2/CommandExecutionRequestApprovalResponse",
  "v2/FileChangeRequestApprovalParams",
  "v2/FileChangeRequestApprovalResponse",
  "v2/PermissionsRequestApprovalParams",
  "v2/PermissionsRequestApprovalResponse",
  "v2/ToolRequestUserInputParams",
  "v2/ToolRequestUserInputResponse",
  "v2/McpServerElicitationRequestResponse",
  "v2/GetAccountParams",
  "v2/GetAccountResponse",
  "v2/GetAccountRateLimitsResponse",
  "v2/AccountRateLimitsUpdatedNotification",
  "v2/LoginAccountParams",
  "v2/LoginAccountResponse",
  "v2/CancelLoginAccountParams",
  "v2/AccountLoginCompletedNotification",
  "v2/UserInput",
  "v2/ThreadItem",
  "v2/Turn",
  "v2/ThreadTokenUsage",
  "v2/RateLimitSnapshot",
  "v2/RateLimitWindow",
  "v2/CommandExecutionApprovalDecision",
  "v2/FileChangeApprovalDecision",
  "v2/WindowsSandboxReadinessResponse",
];

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../src/protocol");
const codex = process.env.CODEX_BIN ?? "codex";

const version = (await run([codex, "--version"])).trim();
const tmp = mkdtempSync(join(tmpdir(), "crewyard-codex-ts-"));
try {
  await run([codex, "app-server", "generate-ts", "--experimental", "--out", tmp]);
  const keep = new Set();
  const queue = [...ROOTS];
  while (queue.length) {
    const name = queue.pop();
    if (keep.has(name)) continue;
    const file = join(tmp, `${name}.ts`);
    if (!existsSync(file)) throw new Error(`generate-ts produced no ${name}.ts`);
    keep.add(name);
    for (const m of readFileSync(file, "utf8").matchAll(/from "(\.{1,2}\/[^"]+)"/g)) {
      queue.push(posix.normalize(posix.join(posix.dirname(name), m[1])));
    }
  }

  rmSync(outDir, { recursive: true, force: true });
  const header = [
    "// Generated by packages/adapter-codex/scripts/gen-protocol.mjs from",
    `// \`codex app-server generate-ts --experimental\` (${version}). Do not edit; rerun the script.`,
    "",
  ].join("\n");
  for (const name of [...keep].sort()) {
    const target = join(outDir, `${name}.ts`);
    mkdirSync(dirname(target), { recursive: true });
    const body = readFileSync(join(tmp, `${name}.ts`), "utf8").replace(/^\/\/ GENERATED CODE!.*\r?\n\r?\n?\/\/ This file was generated by.*\r?\n/m, "");
    writeFileSync(target, header + body.replace(/\r\n/g, "\n"));
  }
  const index = ROOTS.map((r) => `export type * from "./${r}.ts";`).join("\n");
  writeFileSync(join(outDir, "index.ts"), `${header}${index}\n`);
  console.log(`${keep.size} files from ${version} -> ${outDir}`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

async function run(cmd) {
  const res = await runCmd(cmd[0], cmd.slice(1), { timeoutMs: 120_000 });
  if (res.code !== 0) throw new Error(`${cmd.join(" ")} failed: ${res.stderr}`);
  return res.stdout;
}
