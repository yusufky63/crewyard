// Generates packages/ui/src/tokens.css from design/tokens/*.json.
// Run: node scripts/build-tokens.mjs        (write)
//      node scripts/build-tokens.mjs --check (exit 1 when the CSS is out of date)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (name) => JSON.parse(readFileSync(join(root, "design", "tokens", `${name}.json`), "utf8"));
const out = join(root, "packages", "ui", "src", "tokens.css");

const flatten = (node, prefix = [], acc = []) => {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (value && typeof value === "object" && "$value" in value) acc.push([[...prefix, key], value]);
    else if (value && typeof value === "object") flatten(value, [...prefix, key], acc);
  }
  return acc;
};

const cssValue = (token) => {
  const v = token.$value;
  if (token.$type === "fontFamily") return v.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(", ");
  if (token.$type === "cubicBezier") return `cubic-bezier(${v.join(", ")})`;
  return String(v);
};

// color.bg.canvas -> --bg-canvas ; font.size.label -> --font-size-label
const cssName = (path) => `--${(path[0] === "color" ? path.slice(1) : path).join("-")}`;
const block = (selector, entries, extra = "") =>
  `${selector} {\n${extra}${entries.map(([p, t]) => `  ${cssName(p)}: ${cssValue(t)};`).join("\n")}\n}\n`;

const base = read("base");
const { density, ...rest } = base;
const css = [
  "/* Generated by scripts/build-tokens.mjs from design/tokens. Do not edit by hand. */\n",
  block(":root", flatten(rest)),
  block(':root[data-theme="dark"]', flatten(read("dark")), "  color-scheme: dark;\n"),
  block(':root[data-theme="light"]', flatten(read("light")), "  color-scheme: light;\n"),
  ...Object.entries(density).map(([mode, tokens]) => block(`:root[data-density="${mode}"]`, flatten(tokens).map(([p, t]) => [["density", ...p], t]))),
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== css) {
    console.error("packages/ui/src/tokens.css is out of date. Run: pnpm tokens");
    process.exit(1);
  }
  console.log("tokens.css is up to date");
} else {
  writeFileSync(out, css);
  console.log(`wrote ${out}`);
}
